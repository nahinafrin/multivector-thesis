#!/usr/bin/env python3
"""
build_unified_results_report.py
==================================
TARGET LOCATION IN REPO:  step4 dataset/build_unified_results_report.py
(reads existing artifacts only; writes to the repo root as
UNIFIED_RESULTS.md so it sits next to RESULTS_multivector_methodology.md
and methodology_working_multivector.md)

WHY THIS SCRIPT EXISTS
-----------------------
Two evaluation protocols currently coexist without being reconciled:

  Protocol A — "canary-based, negative result" (RESULTS_multivector_methodology.md)
      grounded_controller.jsonl / grounded_baseline.jsonl, 220-row slice,
      neutralization measured by canary integrity, multivector fire rate 0/34,
      the headline claim is a proven negative result plus a defense-in-depth save.

  Protocol B — "marker-based, mitigation ASR" (mitigation_run/, planted200/)
      arm_A/B/C_*.jsonl and report_*.json, smaller planted slices, success
      measured by a success_marker string, headline numbers like ASR 31.0% ->
      18.5% (40.3% relative reduction, p<0.001).

Both are legitimate measurements, but they use different slices, different
success definitions, and were produced at different points in the project's
history (see the git log — the mitigation_run/ track is from the LAST two
commits, after the multivector negative-result writeup was already frozen).
Left as-is, a reader has no way to know which is the current, load-bearing
claim. This script doesn't decide that for you — it mechanically assembles
both protocols' numbers into ONE dated table so the reconciliation becomes an
editorial decision you make with the full picture in front of you, instead of
two documents silently disagreeing.

USAGE
------
    python build_unified_results_report.py
"""
from __future__ import annotations

import json
import subprocess
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(".")

def read_json(path: str) -> dict | None:
    p = Path(path)
    if not p.exists():
        return None
    return json.loads(p.read_text(encoding="utf-8"))

def git_commit_for(path: str) -> str:
    try:
        out = subprocess.run(["git", "log", "-1", "--format=%h %ad", "--date=short", "--", path],
                             capture_output=True, text=True, cwd="..")
        return out.stdout.strip() or "unknown"
    except Exception:
        return "unknown"

def main() -> None:
    protocol_a = {
        "controller": read_json("slice_scoring_controller.json"),
        "baseline": read_json("slice_scoring_baseline.json"),
        "frozen_state": read_json("frozen/thesis_results_locked.json"),
    }
    protocol_b = {
        "planted200_groundplus": read_json("mitigation_results/planted200/report_groundplus.json"),
        "mitigation_run_summary": read_json("mitigation_run/mitigation_summary.json"),
        "stress_run_v2_summary": read_json("stress_run_v2/mitigation_summary.json"),
    }

    lines = []
    lines.append("# Unified Results — Protocol A (canary) vs Protocol B (marker/ASR)")
    lines.append(f"\nGenerated: {datetime.now(timezone.utc).isoformat()}")
    lines.append("\nThis file is generated by build_unified_results_report.py. "
                 "Do not hand-edit; re-run the script after any results file changes.")

    lines.append("\n## Protocol A — canary-based (adversarial_slice.jsonl, 220 rows)")
    lines.append(f"- Source commit for slice_scoring_controller.json: "
                 f"{git_commit_for('step4 dataset/slice_scoring_controller.json')}")
    if protocol_a["controller"]:
        lines.append(f"```json\n{json.dumps(protocol_a['controller'], indent=2)[:2000]}\n```")
    else:
        lines.append("_(slice_scoring_controller.json not found — run score_slice.py first)_")

    lines.append("\n## Protocol B — marker/ASR-based (mitigation_run / planted200)")
    lines.append(f"- Source commit for mitigation_summary.json: "
                 f"{git_commit_for('step4 dataset/mitigation_run/mitigation_summary.json')}")
    for key in ("planted200_groundplus", "mitigation_run_summary", "stress_run_v2_summary"):
        if protocol_b[key]:
            lines.append(f"\n### {key}\n```json\n{json.dumps(protocol_b[key], indent=2)[:2000]}\n```")
        else:
            lines.append(f"\n### {key}\n_(not found / null)_")

    lines.append("\n## Reconciliation checklist (fill in by hand before publishing)")
    lines.append("- [ ] Which protocol's neutralization number is the one cited in the abstract?")
    lines.append("- [ ] Are the two slices' `multivector_attack` / planted-attack rows the SAME "
                "underlying construction, or two different attack designs? (They currently look "
                "like two different designs — canary-leak vs. marker-emission — say so explicitly "
                "if so, rather than letting a reader assume they're the same experiment.)")
    lines.append("- [ ] Is Protocol B's 31.0%->18.5% ASR reduction measured WITH or WITHOUT the "
                "graded-margin fix from 01_revalidate_multivector_graded.py? State this explicitly.")
    lines.append("- [ ] Pick ONE protocol as the headline claim for the abstract/results section; "
                "report the other as a secondary/robustness check, dated and labelled as such.")

    out_path = Path("../UNIFIED_RESULTS.md")
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"[wrote] {out_path.resolve()}")

if __name__ == "__main__":
    main()
