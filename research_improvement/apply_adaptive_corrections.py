def main():
    global E
    if "--set2" in sys.argv:
        E = E2
    if "--set3" in sys.argv:
        E = E3
    apply = "--apply" in sys.argv
    new = {}
    for f in sorted({e["file"] for e in E}):
        raw = (ROOT / f).read_bytes().decode("utf-8")
        crlf = "\r\n" in raw
        t = raw.replace("\r\n", "\n")
        for e in (x for x in E if x["file"] == f):
            n = t.count(e["old"])
            if n != 1:
                raise SystemExit(f"{e['id']}: found {n} times in {f}; nothing written")
            t = t.replace(e["old"], e["new"])
        new[f] = t.replace("\n", "\r\n") if crlf else t
    print(f"{len(E)} edits checked in {len(new)} files")
    if apply:
        for f, t in new.items():
            (ROOT / f).write_bytes(t.encode("utf-8"))
        print("applied")


if __name__ == "__main__":
    main()
